/**
 * Generates `scripts/block-origins.json`: for every block, the dimensions
 * where it generates naturally and whether it can be crafted.
 *
 *   node scripts/build-origins.mjs     (npm run origins)
 *
 * It reads the data pack inside the Minecraft client jar (downloaded and
 * cached by build-models.mjs):
 *
 * - Dimensions: blocks used by each biome's features (ores, trees, plants,
 *   lakes...), each dimension's terrain and surface rules, and structures
 *   (template pools, .nbt templates and processors), mapped to a dimension
 *   through the biomes they can spawn in. Structures built by code instead
 *   of templates (fortress, stronghold, mineshaft...) are listed by hand.
 * - Craftable: a crafting table (or 2x2) recipe produces it. Furnace,
 *   stonecutter and smithing recipes don't count.
 *
 * The output is committed; build-data.mjs reads it, so builds don't need the jar.
 */

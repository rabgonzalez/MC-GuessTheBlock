/* ---------- Minimal NBT reader: every string, with its key ---------- */

function nbtStrings(buffer) {
  const buf = gunzipSync(buffer);
  const out = [];
  let i = 0;
  const str = () => {
    const len = buf.readUInt16BE(i);
    const s = buf.toString("utf8", i + 2, i + 2 + len);
    i += 2 + len;
    return s;
  };
  const payload = (type, key) => {
    switch (type) {
      case 1:
        i += 1;
        break;
      case 2:
        i += 2;
        break;
      case 3:
      case 5:
        i += 4;
        break;
      case 4:
      case 6:
        i += 8;
        break;
      case 7:
        i += 4 + buf.readInt32BE(i);
        break;
      case 8:
        out.push([key, str()]);
        break;
      case 9: {
        const t = buf[i];
        const n = buf.readInt32BE(i + 1);
        i += 5;
        for (let k = 0; k < n; k++) payload(t, key);
        break;
      }
      case 10:
        for (let t = buf[i++]; t !== 0; t = buf[i++]) {
          const name = str();
          payload(t, name);
        }
        break;
      case 11:
        i += 4 + buf.readInt32BE(i) * 4;
        break;
      case 12:
        i += 4 + buf.readInt32BE(i) * 8;
        break;
      default:
        throw new Error(`NBT tag ${type}`);
    }
  };
  const type = buf[i++];
  str();
  payload(type, "");
  return out;
}


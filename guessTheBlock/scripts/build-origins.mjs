/** A worldgen file an id points to (feature, pool, processors, template). */
function referenced(id) {
  return [
    join(DATA, "worldgen", "placed_feature", `${id}.json`),
    join(DATA, "worldgen", "configured_feature", `${id}.json`),
    join(DATA, "worldgen", "template_pool", `${id}.json`),
    join(DATA, "worldgen", "processor_list", `${id}.json`),
    join(DATA, "structure", `${id}.nbt`),
  ].filter((f) => existsSync(f));
}

function addBlock(value, blocks) {
  const id = strip(value.replace(/[[{].*$/, ""));
  const name = ALIASES[id] ?? id;
  if (BLOCKS.has(name)) blocks.add(name);
}

/** [key, string] pairs of a JSON value, plus feature types found. */
function jsonStrings(value, key, out, types) {
  if (typeof value === "string") out.push([key, value]);
  else if (Array.isArray(value))
    value.forEach((v) => jsonStrings(v, key, out, types));
  else if (value && typeof value === "object") {
    if (typeof value.type === "string") types.push(strip(value.type));
    // Multiface features (glow lichen, sculk vein) name their block as "block".
    if (value.type === "minecraft:multiface_growth" || key === "config") {
      if (typeof value.block === "string") out.push(["Name", value.block]);
    }
    for (const [k, v] of Object.entries(value)) jsonStrings(v, k, out, types);
  }
}

/** Blocks placed by a JSON or NBT file, following feature/pool/template ids. */
async function collect(file, blocks) {
  if (visited.has(file)) return;
  visited.add(file);
  let pairs = [];
  const types = [];
  if (file.endsWith(".nbt")) pairs = nbtStrings(await readFile(file));
  else jsonStrings(JSON.parse(await readFile(file, "utf8")), "", pairs, types);
  for (const t of types)
    (FEATURE_TYPES[t] ?? []).forEach((b) => addBlock(b, blocks));
  for (const [key, value] of pairs) {
    if (BLOCK_KEYS.has(key)) addBlock(value, blocks);
    if (!REF_KEYS.has(key)) continue;
    for (const ref of referenced(strip(value))) await collect(ref, blocks);
  }
}

/** Blocks of several entry points, with a fresh visited set. */
async function blocksOf(files) {
  visited.clear();
  const blocks = new Set();
  for (const f of files) await collect(f, blocks);
  return blocks;
}

/* ---------- Biomes -> dimension ---------- */

async function tagValues(tag, seen = new Set()) {
  const path = join(DATA, "tags", "worldgen", "biome", `${strip(tag)}.json`);
  if (seen.has(path) || !existsSync(path)) return [];
  seen.add(path);
  const out = [];
  for (const v of (await readJson(path)).values) {
    const id = typeof v === "string" ? v : v.id;
    if (id.startsWith("#")) out.push(...(await tagValues(id.slice(1), seen)));
    else out.push(strip(id));
  }
  return out;
}

const nether = new Set(await tagValues("is_nether"));
const end = new Set(await tagValues("is_end"));
const dimensionOf = (biome) =>
  nether.has(biome) ? "nether" : end.has(biome) ? "end" : "overworld";

const found = new Map(); // block -> Set of dimensions
/** `DEBUG=stone node scripts/build-origins.mjs` shows where a block comes from. */
const debug = process.env.DEBUG;
const add = (blocks, dims, source) => {
  if (debug && blocks.has(debug)) console.log(debug, dims.join("+"), source);
  for (const b of blocks) {
    if (!found.has(b)) found.set(b, new Set());
    dims.forEach((d) => found.get(b).add(d));
  }
};

// 1. Terrain: default blocks, fluids and surface rules of each dimension.
const NOISE = {
  overworld: [
    "overworld",
    "amplified",
    "large_biomes",
    "caves",
    "floating_islands",
  ],
  nether: ["nether"],
  end: ["end"],
};
for (const [dim, files] of Object.entries(NOISE)) {
  const blocks = await blocksOf(
    files.map((f) => join(DATA, "worldgen", "noise_settings", `${f}.json`))
  );
  add(blocks, [dim], `terrain ${dim}`);
}

// 2. Biome features: ores, trees, plants, lakes, fossils...
for (const file of await readdir(join(DATA, "worldgen", "biome"))) {
  const biome = file.replace(/\.json$/, "");
  const blocks = await blocksOf([join(DATA, "worldgen", "biome", file)]);
  add(blocks, [dimensionOf(biome)], `biome ${biome}`);
}

// 3. Structures, in the dimensions of the biomes they spawn in.
for (const file of await readdir(join(DATA, "worldgen", "structure"))) {
  const json = await readJson(join(DATA, "worldgen", "structure", file));
  const biomes =
    typeof json.biomes === "string"
      ? await tagValues(json.biomes.slice(1))
      : json.biomes.map(strip);
  const dims = [...new Set(biomes.map(dimensionOf))];
  const entry = [];
  if (json.start_pool) {
    entry.push(
      join(DATA, "worldgen", "template_pool", `${strip(json.start_pool)}.json`)
    );
  }
  const folder = TEMPLATE_FOLDERS[json.type];
  if (folder) {
    const dir = join(DATA, "structure", folder);
    for (const f of await readdir(dir, { recursive: true })) {
      if (f.endsWith(".nbt")) entry.push(join(dir, f));
    }
  }
  const blocks = await blocksOf(entry);
  (CODE_STRUCTURES[json.type] ?? []).forEach((b) => blocks.add(b));
  if (json.type === "minecraft:ruined_portal") {
    if (dims.includes("nether")) {
      PORTAL_STONE.forEach((b) => blocks.delete(b));
      NETHER_PORTAL_BRICKS.forEach((b) => blocks.add(b));
    } else {
      ["mossy_stone_bricks", "vine"].forEach((b) => blocks.add(b));
    }
  }
  add(blocks, dims, `structure ${file}`);
}

for (const [block, dims] of Object.entries(EXTRA)) {
  add(new Set([block]), dims, "extra");
}

/* ---------- Crafting recipes ---------- */

const craftable = new Set();
for (const file of await readdir(join(DATA, "recipe"))) {
  const recipe = await readJson(join(DATA, "recipe", file));
  const id = recipe.result?.id ?? recipe.result?.item;
  if (recipe.type.startsWith("minecraft:crafting") && id) {
    craftable.add(strip(id));
  }
}

/* ---------- Output ---------- */

const ORDER = ["overworld", "nether", "end"];
const origins = {};
for (const name of [...BLOCKS].sort()) {
  const dims = [...(found.get(name) ?? [])].sort(
    (a, b) => ORDER.indexOf(a) - ORDER.indexOf(b)
  );
  origins[name] = { dimensions: dims, craftable: craftable.has(name) };
}
await writeFile(OUT, JSON.stringify(origins, null, 1) + "\n");
console.log(
  `block-origins.json: ${found.size} natural blocks, ${craftable.size} craftable items`
);
